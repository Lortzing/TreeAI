interface RegistryFixtureEntry {
  readonly [key: string]: unknown;
}
interface Registry {
  readonly kind: string;
  readonly fixtures: readonly RegistryFixtureEntry[];
  readonly negativeFixtures: readonly RegistryFixtureEntry[];
  readonly versionPairs: readonly Record<string, unknown>[];
}
interface ExpectedTruth {
  readonly fixtureId: string;
  readonly normalizer: string;
  readonly canonicalText: string;
  readonly blocks: readonly {
    blockId: string;
    kind: string;
    start: number;
    end: number;
    page?: number;
    text: string;
  }[];
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return typeof value === "object" && value !== null && !Array.isArray(value) ? (value as Record<string, unknown>) : null;
}
function asString(value: unknown): string | null {
  return typeof value === "string" ? value : null;
}
function asArray(value: unknown): unknown[] | null {
  return Array.isArray(value) ? value : null;
}

function readJson(path: string, problems: string[], what: string): Record<string, unknown> | null {
  try {
    const parsed = JSON.parse(readFileSync(path, "utf8")) as unknown;
    const record = asRecord(parsed);
    if (record === null) {
      problems.push(`${what}: not a JSON object at ${path}`);
      return null;
    }
    return record;
  } catch (error) {
    problems.push(`${what}: unreadable/invalid JSON at ${path} (${error instanceof Error ? error.message : String(error)})`);
    return null;
  }
}

function loadExpected(path: string, problems: string[], fixtureId: string): ExpectedTruth | null {
  const raw = readJson(path, problems, `b1 expected ${fixtureId}`);
  if (raw === null) return null;
  const fixtureIdF = asString(raw["fixtureId"]);
  const normalizer = asString(raw["normalizer"]);
  const canonicalText = asString(raw["canonicalText"]);
  const blocksRaw = asArray(raw["blocks"]);
  if (canonicalText === null || blocksRaw === null) {
    problems.push(`b1 expected ${fixtureId}: missing canonicalText/blocks`);
    return null;
  }
  const blocks: { blockId: string; kind: string; start: number; end: number; page?: number; text: string }[] = [];
  for (const b of blocksRaw) {
    const r = asRecord(b);
    if (r === null) {
      problems.push(`b1 expected ${fixtureId}: non-object block entry`);
      return null;
    }
    const blockId = asString(r["blockId"]);
    const kind = asString(r["kind"]);
    const text = asString(r["text"]);
    const start = r["start"];
    const end = r["end"];
    if (blockId === null || kind === null || text === null || typeof start !== "number" || typeof end !== "number") {
      problems.push(`b1 expected ${fixtureId}: malformed block entry`);
      return null;
    }
    const page = r["page"];
    blocks.push({ blockId, kind, start, end, text, ...(typeof page === "number" ? { page } : {}) });
  }
  return {
    fixtureId: fixtureIdF ?? fixtureId,
    normalizer: normalizer ?? "?",
    canonicalText,
    blocks,
  };
}

