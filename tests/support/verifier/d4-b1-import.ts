/**
 * Shared B1「导入/版本」executing check (D4-1 wave, issue #8 charter §6 B1).
 *
 * Runs the REAL import pipeline (MaterialImportService + MaterialRepository +
 * the wired d4-md-v1 / d4-pdf-v1 parsers) in a throwaway SQLite database
 * against whatever b1-import registries exist at runtime:
 *
 *  - md-registry.json AND pdf-registry.json are enumerated generically (either
 *    may be absent while its parallel wave is in flight);
 *  - every registered READY fixture must round-trip to its frozen
 *    *.expected.json truth byte-exactly (canonicalText + full block map,
 *    incl. pdf page numbers), and re-importing the same bytes must REUSE the
 *    version (zero new rows — 重复导入不重复版本);
 *  - every registered NEGATIVE must be honestly rejected: either at the
 *    import gate (honest error type, zero persistence — e.g. an empty file)
 *    or as a terminal failed version whose parseError carries the frozen
 *    reason code; a ready outcome is a FAIL (不得伪装成功空文档);
 *  - registered version pairs, when their source files are locatable, must
 *    append a second version with the old version still readable and both
 *    truths intact (改版保留旧来源); pairs whose source files cannot be
 *    located are reported as not executed (registration-only), not silently
 *    dropped and not a failure;
 *  - when tests/fixtures/d4/manifest.json registers generatedOversize probes
 *    (3 charter §5 negatives: >20 MiB / >200 pages / >1M UTF-16 units), the
 *    three probes are generated deterministically HERE and executed: each
 *    must be rejected before exhausting resources with the matching reason
 *    (material-too-large / pages-exceeded / text-units-exceeded). If the
 *    manifest is absent the probes are reported as not registered — not a
 *    failure (the parallel wave owns that file).
 *
 * Consumers: scripts/verify-d4.js (check `b1-import-versions`). The frozen
 * fixture tree stays read-only — nothing under tests/fixtures/d4 is written
 * or regenerated by this check.
 */

import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { MaterialRepository, TreeRepository } from "@treeai/persistence";
import type { MaterialId, MaterialVersion, MaterialVersionId, TreeId } from "@treeai/contracts";
import {
  MaterialImportService,
  MaterialNotReadyError,
  MaterialTooLargeError,
  MaterialUnsupportedError,
} from "../../../apps/studio/src/materials/import-service.ts";

export interface B1ImportCheckOutcome {
  readonly status: "PASS" | "FAIL" | "NOT_RUN";
  readonly exitCode: number | null;
  /** One-line summary for the check matrix. */
  readonly detail: string;
  /** Per-fixture execution lines (evidence log). */
  readonly lines: readonly string[];
  readonly problems: readonly string[];
}

